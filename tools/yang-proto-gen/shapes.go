package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/openconfig/goyang/pkg/yang"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"

	"github.com/Vikasa2M/openits-models/internal/wireshape"
)

// eventRootEntries returns mod's live top-level notifications: each one is a
// root message in its service's events.proto.
func eventRootEntries(mod *yang.Entry) []*yang.Entry {
	var out []*yang.Entry
	for _, c := range sortedChildren(mod) {
		if c.Kind != yang.NotificationEntry {
			continue
		}
		if st := entryStatus(c); st == "deprecated" || st == "obsolete" {
			continue
		}
		out = append(out, c)
	}
	return out
}

// configStateRootEntries returns mod's live top-level containers and lists:
// each one is a root message in its service's state.proto when mod is on the
// configStateRoutes allowlist.
func configStateRootEntries(mod *yang.Entry) []*yang.Entry {
	var out []*yang.Entry
	for _, c := range sortedChildren(mod) {
		if c.Kind == yang.NotificationEntry {
			continue
		}
		if c.RPC != nil {
			continue // top-level rpc statements aren't config/state trees
		}
		if st := entryStatus(c); st == "deprecated" || st == "obsolete" {
			continue
		}
		if !c.IsContainer() && !c.IsList() {
			continue
		}
		out = append(out, c)
	}
	return out
}

// moduleRootNames maps each module that puts messages on the wire to the
// full proto names of its root messages, in Generate's emission order.
func moduleRootNames(mods []*yang.Entry) map[string][]protoreflect.FullName {
	out := map[string][]protoreflect.FullName{}
	for _, mod := range mods {
		if pkg, _, ok := pkgFor(mod.Name); ok {
			for _, c := range eventRootEntries(mod) {
				out[mod.Name] = append(out[mod.Name], protoreflect.FullName(pkg+"."+ProtoName(c.Name)))
			}
		}
		if route, ok := configStateFor(mod.Name); ok {
			for _, c := range configStateRootEntries(mod) {
				out[mod.Name] = append(out[mod.Name], protoreflect.FullName(route.pkg+"."+ProtoName(c.Name)))
			}
		}
	}
	return out
}

const shapeHeader = `// Wire shape of %s. Generated by ` + "`make gen`" + `; do not edit.
//
// Every message and enum this module's root messages can put on the wire,
// rendered canonically from the compiled descriptors: types by full name,
// fields in number order, comments and declaration order dropped. A module
// revision's schema-registry snapshot pins this file as schema.shape, and
// check-revisions fails when it changes without a new revision. See
// docs/versioning.md.
//
`

// ShapeFile renders the schema.shape text for one module: the header, one
// "root <name> <digest>" line per root (the digest covers that root's own
// closure), and the canonical rendering of the closure of all roots.
func ShapeFile(module string, roots []protoreflect.MessageDescriptor) string {
	var b strings.Builder
	fmt.Fprintf(&b, shapeHeader, module)
	for _, r := range roots {
		fmt.Fprintf(&b, "// root %s %s\n", r.FullName(), wireshape.Digest(r))
	}
	b.WriteByte('\n')
	b.WriteString(wireshape.Render(roots...))
	return b.String()
}

// OwnProtoFile renders the schema.proto text for one module: only the
// messages the module itself declares, as a compilable file in their own
// package. Shared types it reaches in other files are imported, and pinned
// by schema.shape rather than repeated here.
func OwnProtoFile(module string, roots []protoreflect.MessageDescriptor) (string, error) {
	byFile := map[string]protoreflect.FileDescriptor{}
	var rootsIn = map[string][]protoreflect.MessageDescriptor{}
	for _, r := range roots {
		f := r.ParentFile()
		byFile[f.Path()] = f
		rootsIn[f.Path()] = append(rootsIn[f.Path()], r)
	}
	paths := make([]string, 0, len(byFile))
	for p := range byFile {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var msgs []protoreflect.MessageDescriptor
	pkg := byFile[paths[0]].Package()
	for _, p := range paths {
		if byFile[p].Package() != pkg {
			return "", fmt.Errorf("module %s has root messages in two packages (%s, %s)", module, pkg, byFile[p].Package())
		}
		msgs = append(msgs, wireshape.Own(byFile[p], rootsIn[p]...)...)
	}
	header := []string{
		"Messages " + module + " declares in " + strings.Join(paths, ", ") + ". Generated by `make gen`; do not edit.",
		"",
		"Types it reaches in other files are imported, not repeated: schema.shape",
		"pins their shape. Messages other modules declare in the same file are",
		"left out.",
	}
	return wireshape.RenderFile(byFile[paths[0]], msgs, header), nil
}

// GenerateShapes writes <module>.shape and <module>.proto into outDir for
// every module with root messages, resolving roots in the compiled
// descriptor set at descriptorPath, and removes files left over from
// modules that no longer have roots.
func GenerateShapes(yangDir, descriptorPath, outDir string) error {
	if descriptorPath == "" {
		return fmt.Errorf("shapes: -descriptors is required")
	}
	_, mods, err := LoadModules(yangDir)
	if err != nil {
		return fmt.Errorf("shapes: load yang modules from %s: %w", yangDir, err)
	}
	raw, err := os.ReadFile(descriptorPath)
	if err != nil {
		return fmt.Errorf("shapes: %w", err)
	}
	var set descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(raw, &set); err != nil {
		return fmt.Errorf("shapes: parse %s: %w", descriptorPath, err)
	}
	files, err := protodesc.NewFiles(&set)
	if err != nil {
		return fmt.Errorf("shapes: link %s: %w", descriptorPath, err)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	written := map[string]bool{}
	names := moduleRootNames(mods)
	modules := make([]string, 0, len(names))
	for m := range names {
		modules = append(modules, m)
	}
	sort.Strings(modules)
	for _, m := range modules {
		var roots []protoreflect.MessageDescriptor
		for _, n := range names[m] {
			d, err := files.FindDescriptorByName(n)
			if err != nil {
				return fmt.Errorf("shapes: module %s root %s is not in the compiled protos: %w", m, n, err)
			}
			md, ok := d.(protoreflect.MessageDescriptor)
			if !ok {
				return fmt.Errorf("shapes: module %s root %s is not a message", m, n)
			}
			roots = append(roots, md)
		}
		own, err := OwnProtoFile(m, roots)
		if err != nil {
			return fmt.Errorf("shapes: %w", err)
		}
		for name, content := range map[string]string{m + ".shape": ShapeFile(m, roots), m + ".proto": own} {
			if err := os.WriteFile(filepath.Join(outDir, name), []byte(content), 0o644); err != nil {
				return err
			}
			written[name] = true
		}
	}
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		n := e.Name()
		if (strings.HasSuffix(n, ".shape") || strings.HasSuffix(n, ".proto")) && !written[n] {
			if err := os.Remove(filepath.Join(outDir, n)); err != nil {
				return err
			}
		}
	}
	return nil
}
